for (const [raw, title, year] of cases) {
  test(`ניקוי שם: ${raw.slice(0, 52)}`, () => {
    const p = parseName(raw)
    expect(p.title).toBe(title)
    if (year !== undefined) expect(p.year).toBe(year)
  })
}

test('חלקי סרט נשמרים כמספר חלק ולא נשארים בכותרת', () => {
  expect(parseName('שאטר איילנד 2010 חלק 3.mp4').part).toBe(3)
  expect(parseName('האירי ח2.mp4').part).toBe(2)
  expect(parseName("טלי_אברהמי_בלי_לחץ_המופע_ח''ג.mp4").part).toBe(3)
})

test('מספר הפרק לא נבלע על ידי שם קבוצת הריפ שאחריו', () => {
  // התבנית "<טוקן> סרטים" בלעה את "פ1" שלפניה, והפרק נעלם בשקט —
  // ואז שלושה פרקים של אותה סדרה הופיעו כשלושה סרטים נפרדים
  const p = parseName('אגדת הים הכחול ע1 פ1 סרטים וסדרות בדרייב or.avi')
  expect(p.season).toBe(1)
  expect(p.episode).toBe(1)
})

test('מספר עונה שכתוב במילים מזוהה בתיקיית עונה', () => {
  // בלי זה התיקייה מקבלת מספר לפי סדר סיום הסריקה המקבילית,
  // כלומר סדר אחר בכל סריקה
  expect(parseSeasonFolder('עונה שלוש').number).toBe(3)
  expect(parseSeasonFolder('עונה ראשונה').number).toBe(1)
  expect(parseSeasonFolder('עונה 7').number).toBe(7)
  expect(parseSeasonFolder('חומרים נוספים').number).toBeNull()
})

test('חתימת סרטים השחר מוסרת משם Drive לפני התאמת TMDB', () => {
  const parsed = parseName('The.Batman.2022.1080p.WEBRip.x264.סרטים_השחר.mkv')
  expect(parsed.title).toBe('The Batman')
  expect(parsed.year).toBe(2022)
})
